// Language management
let currentAdminLanguage = localStorage.getItem('adminLanguage') || 'en';

function setAdminLanguage(lang) {
    currentAdminLanguage = lang;
    localStorage.setItem('adminLanguage', lang);
    
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === lang);
    });
    
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.dataset.i18n;
        if (adminTranslations[lang] && adminTranslations[lang][key]) {
            element.textContent = adminTranslations[lang][key];
        }
    });
    
    document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
        const key = element.dataset.i18nPlaceholder;
        if (adminTranslations[lang] && adminTranslations[lang][key]) {
            element.placeholder = adminTranslations[lang][key];
        }
    });
    
    document.documentElement.lang = lang === 'am' ? 'am' : 'en';
}

document.addEventListener('DOMContentLoaded', () => {
    setAdminLanguage(currentAdminLanguage);
});

window.adminTranslations = adminTranslations;
window.setAdminLanguage = setAdminLanguage;